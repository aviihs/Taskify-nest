import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayNotEmpty,
  IsArray,
  IsBoolean,
  IsDate,
  IsIn,
  IsInt,
  IsMongoId,
  IsNotEmpty,
  IsOptional,
  IsString,
  Matches,
  Max,
  MaxLength,
  Min,
} from 'class-validator';
import { MAX_MESSAGE_LENGTH } from '../schemas/chat-message.schema';

export const AVAILABILITIES = ['ONLINE', 'OFFLINE'] as const;
export type Availability = (typeof AVAILABILITIES)[number];

export class OpenDirectConversationDto {
  @ApiProperty({ description: 'Workspace both people belong to' })
  @IsMongoId()
  workspaceId: string;

  @ApiProperty({ description: 'The person to message' })
  @IsMongoId()
  userId: string;
}

export class SendMessageDto {
  @ApiProperty({ example: 'Can you take a look at the pricing page?' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(MAX_MESSAGE_LENGTH)
  body: string;

  @ApiPropertyOptional({
    description:
      'Idempotency key generated by the device; retrying with the same key never creates a duplicate',
    example: '3b2f6a2e-4f1c-4d8e-9a57-0c3c3b1d9e11',
  })
  @IsOptional()
  @IsString()
  @Matches(/^[A-Za-z0-9_-]{8,64}$/, {
    message: 'clientId must be 8-64 letters, digits, - or _',
  })
  clientId?: string;

  @ApiPropertyOptional({ description: 'The text was forwarded from a chat' })
  @IsOptional()
  @IsBoolean()
  forwarded?: boolean;
}

export const MAX_DELETE_BATCH = 100;

export class DeleteMessagesDto {
  @ApiProperty({ type: [String], maxItems: MAX_DELETE_BATCH })
  @IsArray()
  @ArrayNotEmpty()
  @ArrayMaxSize(MAX_DELETE_BATCH)
  @IsMongoId({ each: true })
  messageIds: string[];

  @ApiPropertyOptional({
    description:
      'Delete for everyone (only your own messages); otherwise only for you',
    default: false,
  })
  @IsOptional()
  @IsBoolean()
  forEveryone?: boolean;
}

export class ListMessagesQueryDto {
  @ApiPropertyOptional({
    description: 'Older page: messages with seq below this',
  })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  before?: number;

  @ApiPropertyOptional({
    description: 'Catch-up after reconnecting: messages with seq above this',
  })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(0)
  after?: number;

  @ApiPropertyOptional({ minimum: 1, maximum: 100, default: 30 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(100)
  limit = 30;
}

export class ListConversationsQueryDto {
  @ApiPropertyOptional({
    description: 'Next page: conversations whose last message is older',
  })
  @IsOptional()
  @Type(() => Date)
  @IsDate()
  before?: Date;

  @ApiPropertyOptional({ minimum: 1, maximum: 100, default: 30 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(100)
  limit = 30;
}

export class MarkReadDto {
  @ApiProperty({ description: 'Highest message seq the user has seen' })
  @Type(() => Number)
  @IsInt()
  @Min(0)
  seq: number;
}

export class ContactsQueryDto {
  @ApiProperty()
  @IsMongoId()
  workspaceId: string;

  @ApiPropertyOptional({ description: 'Filter by name or username' })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  q?: string;
}

export class UpdatePresenceDto {
  @ApiProperty({ enum: AVAILABILITIES })
  @IsIn(AVAILABILITIES)
  availability: Availability;
}
